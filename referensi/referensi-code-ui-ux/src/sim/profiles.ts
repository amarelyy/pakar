function knotsFor(archetype: ZoneArchetype, day: number): Knots {
  const p = PROFILES[archetype]
  if (day === 0) return p.sunday
  if (day === 6) return p.saturday
  return p.weekday
}

/** Smooth (C1) baseline occupancy for an archetype at sim time t. */
export function profileOccupancy(archetype: ZoneArchetype, t: number): number {
  const day = dayOfWeek(t)
  const h = hourOfDay(t)
  const h0 = Math.floor(h)
  const s = smoothstep(h - h0)
  const k = knotsFor(archetype, day)
  const next = h0 === 23 ? knotsFor(archetype, dayOfWeek(t + DAY_MS))[0] : k[h0 + 1]
  return k[h0] + (next - k[h0]) * s
}
