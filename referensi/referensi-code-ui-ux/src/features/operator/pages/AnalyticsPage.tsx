import clsx from 'clsx'
import { useMemo, useState } from 'react'
import { NavLink } from 'react-router-dom'
import { Heatmap } from '@/components/charts/Heatmap'
import { OccupancyChart } from '@/components/charts/OccupancyChart'
import { KpiTile } from '@/components/ui/KpiTile'
import { Table, Td, Th } from '@/components/ui/Table'
import { fmtCount, fmtPct, fmtPctDelta } from '@/lib/format'
import { DAY_MS, HOUR_MS, STEP_MS, dayOfWeek, hourOfDay, startOfDay, stepIndex, stepStart } from '@/lib/time'
import { stepOccupancy } from '@/sim/engine'
import { evaluateForecasts, flowFor, forecastTrace, heatmap, typicalPeak } from '@/sim/history'
import { ZONES, ZONE_BY_ID } from '@/sim/zones'
import { useLives, useNow } from '@/store/derived'
import { Card, PageHeader } from '../parts'

export function AnalyticsPage({ tab }: { tab: 'patterns' | 'forecast' }) {
  const now = useNow()
  const [zoneId, setZoneId] = useState<string>('all')
  const tabs = (
    <div className="flex items-center gap-1 rounded-card border border-hairline bg-ground p-0.5">
      {[
        { to: '/ops/analytics', label: 'Patterns', end: true },
        { to: '/ops/analytics/forecast', label: 'Forecast health' },
      ].map((t) => (
        <NavLink key={t.to} to={t.to} end={t.end} className={({ isActive }) => clsx('rounded-[6px] px-3 py-1.5 text-sm font-medium', isActive ? 'bg-card text-ink shadow-[0_1px_2px_rgba(20,24,31,0.08)]' : 'text-muted hover:text-ink')}>
          {t.label}
        </NavLink>
      ))}
    </div>
  )
  return (
    <div className="pb-8">
      <PageHeader title="Analytics" subtitle="Eight weeks of history, generated by the same model that drives the live view" right={tabs} />
      <div className="mb-3 flex items-center gap-2 px-6">
        <label htmlFor="zone" className="text-xs text-muted">
          Zone
        </label>
        <select id="zone" value={zoneId} onChange={(e) => setZoneId(e.target.value)} className="h-9 rounded-card border border-hairline bg-card px-2 text-sm">
          <option value="all">All zones</option>
          {ZONES.map((z) => (
            <option key={z.id} value={z.id}>
              {z.name}
            </option>
          ))}
        </select>
      </div>
      {tab === 'patterns' ? <Patterns now={now} zoneId={zoneId} /> : <ForecastHealth now={now} zoneId={zoneId} />}
    </div>
  )
}

function Patterns({ now, zoneId }: { now: number; zoneId: string }) {
  const lives = useLives()
  const hour = Math.floor(now / HOUR_MS)
  const grid = useMemo(() => {
    if (zoneId !== 'all') return heatmap(ZONE_BY_ID[zoneId])
    const g: number[][] = Array.from({ length: 7 }, () => new Array<number>(24).fill(0))
    const cap = ZONES.reduce((s, z) => s + z.capacity, 0)
    for (const z of ZONES) {
      const h = heatmap(z)
      for (let d = 0; d < 7; d++) for (let k = 0; k < 24; k++) g[d][k] += (h[d][k] * z.capacity) / cap
    }
    return g
  }, [zoneId])
  const league = useMemo(
    () =>
      ZONES.map((z) => {
        const f = flowFor(z, now)
        const tp = typicalPeak(z, now)
        return { z, f, tp }
      }).sort((a, b) => b.f.peakOccupancy - a.f.peakOccupancy),
    [hour], // eslint-disable-line react-hooks/exhaustive-deps
  )
  const util = league.reduce((s, r) => s + r.f.peakOccupancy * r.z.capacity, 0) / ZONES.reduce((s, z) => s + z.capacity, 0)
  return (
    <>
      <div className="grid grid-cols-3 gap-3 px-6">
        <KpiTile label="Peak occupancy today" value={fmtPct(util)} foot="capacity-weighted across all zones" />
        <KpiTile label="Median dwell today" value={`${Math.round(league.map((r) => r.f.dwellMin).sort((a, b) => a - b)[Math.floor(league.length / 2)])}`} unit="min" foot="across zones, by Little's law on modelled churn" />
        <KpiTile label="Zones over 90 % at peak" value={fmtCount(league.filter((r) => r.f.peakOccupancy > 0.9).length)} unit={`of ${ZONES.length}`} foot="candidates for pricing or signage changes" />
      </div>
      <div className="mt-3 grid grid-cols-3 gap-3 px-6">
        <Card title="Usual occupancy by weekday and hour" subtitle={zoneId === 'all' ? 'All zones, capacity-weighted, last 8 weeks' : `${ZONE_BY_ID[zoneId].name}, last 8 weeks`}>
          <Heatmap grid={grid} highlightDay={dayOfWeek(now)} highlightHour={Math.floor(hourOfDay(now))} />
        </Card>
        <Card title="Utilisation league" subtitle="Today's peak vs the 4-week average for this weekday" className="col-span-2" padded={false}>
          <Table>
            <thead>
              <tr>
                <Th>Zone</Th>
                <Th numeric>Peak today</Th>
                <Th numeric>Usual peak</Th>
                <Th numeric>Change</Th>
                <Th numeric>Peak hour</Th>
                <Th numeric>Dwell</Th>
                <Th numeric>Turnover</Th>
                <Th numeric>Arrivals</Th>
              </tr>
            </thead>
            <tbody>
              {league.map(({ z, f, tp }) => {
                const delta = (f.peakOccupancy - tp.peak) * 100
                return (
                  <tr key={z.id} className={clsx(!lives[z.id].isOpen && 'text-muted')}>
                    <Td>
                      <span className="font-medium text-ink">{z.shortName}</span> <span className="text-xs text-muted">{z.code}</span>
                    </Td>
                    <Td numeric>{fmtPct(f.peakOccupancy)}</Td>
                    <Td numeric className="text-muted">
                      {fmtPct(tp.peak)}
                    </Td>
                    <Td numeric className={clsx('text-xs', Math.abs(delta) >= 5 && (delta > 0 ? 'text-warn-ink' : 'text-ok-ink'))}>
                      {fmtPctDelta(delta)}
                    </Td>
                    <Td numeric className="text-xs">
                      {String(f.peakHour).padStart(2, '0')}:00
                    </Td>
                    <Td numeric className="text-xs">
                      {Math.round(f.dwellMin)} min
                    </Td>
                    <Td numeric className="text-xs">
                      {f.turnoverPerBay.toFixed(1)} /bay
                    </Td>
                    <Td numeric className="text-xs">
                      {Math.round(f.arrivalsPerHour)} veh/h
                    </Td>
                  </tr>
                )
              })}
            </tbody>
          </Table>
        </Card>
      </div>
    </>
  )
}

function ForecastHealth({ now, zoneId }: { now: number; zoneId: string }) {
  const lives = useLives()
  const hour = Math.floor(now / HOUR_MS)
  const from = stepIndex(now - 7 * DAY_MS)
  const to = stepIndex(now)
  const perZone = useMemo(() => ZONES.map((z) => ({ z, acc: evaluateForecasts(z, from, to) })), [hour]) // eslint-disable-line react-hooks/exhaustive-deps
  const summary = [15, 30, 60].map((h, i) => {
    const n = perZone.reduce((s, r) => s + r.acc[i].n, 0)
    return {
      h,
      mae: perZone.reduce((s, r) => s + r.acc[i].maeBays * r.acc[i].n, 0) / Math.max(1, n),
      hit: perZone.reduce((s, r) => s + r.acc[i].hitRate * r.acc[i].n, 0) / Math.max(1, n),
    }
  })
  const focus = zoneId === 'all' ? ZONES[0] : ZONE_BY_ID[zoneId]
  const overlay = useMemo(() => {
    const f = Math.max(startOfDay(now) + 5 * HOUR_MS, now - 12 * HOUR_MS)
    const i0 = stepIndex(f)
    const actual = []
    for (let i = i0; i <= to; i++) actual.push({ t: stepStart(f) + (i - i0) * STEP_MS, u: stepOccupancy(focus, i) })
    const trace = forecastTrace(focus, i0, to, 12)
    return { from: f, to: now, actual, trace }
  }, [focus, hour]) // eslint-disable-line react-hooks/exhaustive-deps

  return (
    <>
      <div className="grid grid-cols-3 gap-3 px-6">
        {summary.map((s) => (
          <KpiTile key={s.h} label={`${s.h}-minute forecast, last 7 days`} value={s.mae.toFixed(1)} unit="bays typical error" foot={`${fmtPct(s.hit)} of outcomes landed inside the shown range`} />
        ))}
      </div>
      <div className="mt-3 grid grid-cols-3 gap-3 px-6">
        <Card title={`What the 60-minute forecast said vs what happened · ${focus.shortName}`} subtitle="Solid: measured. Dotted with band: the forecast issued an hour earlier for that moment." className="col-span-2">
          <OccupancyChart capacity={focus.capacity} actual={overlay.actual} forecast={overlay.trace} now={now + DAY_MS} from={overlay.from} to={overlay.to} yMode="occupancy" height={220} labelNow={false} />
        </Card>
        <Card title="How to read this" subtitle="Plain words, no model jargon">
          <ul className="space-y-2 text-xs text-muted">
            <li>Each forecast blends the zone's usual weekday profile with how today has been running and any known campus event, then fades back toward usual as the horizon grows.</li>
            <li>The range is set so that roughly 7 in 10 outcomes land inside it. Well above that means the range is wider than it needs to be; well below means the lot changes faster than the model expects.</li>
            <li>Typical error is in bays, not percent, so a small lot and a large one can be compared by what a driver would notice.</li>
            <li>A zone marked <strong>check</strong> has drifted outside the 55–90 % coverage band and deserves a look at its sensors or its profile.</li>
          </ul>
        </Card>
      </div>
      <div className="mx-6 mt-3 rounded-card border border-hairline bg-card">
        <Table>
          <thead>
            <tr>
              <Th>Zone</Th>
              <Th numeric>Error 15 min</Th>
              <Th numeric>Error 30 min</Th>
              <Th numeric>Error 60 min</Th>
              <Th numeric>In range 15</Th>
              <Th numeric>In range 30</Th>
              <Th numeric>In range 60</Th>
              <Th numeric>Bias 60</Th>
              <Th>Drift</Th>
            </tr>
          </thead>
          <tbody>
            {perZone.map(({ z, acc }) => {
              const drift = acc.some((a) => a.n > 50 && (a.hitRate < 0.55 || a.hitRate > 0.9))
              return (
                <tr key={z.id} className={clsx(!lives[z.id].online && 'text-muted')}>
                  <Td>
                    <span className="font-medium text-ink">{z.shortName}</span> <span className="text-xs text-muted">{fmtCount(z.capacity)} bays</span>
                  </Td>
                  {acc.map((a) => (
                    <Td key={`e${a.horizonMin}`} numeric className="text-xs">
                      {a.maeBays.toFixed(1)} bays
                    </Td>
                  ))}
                  {acc.map((a) => (
                    <Td key={`h${a.horizonMin}`} numeric className={clsx('text-xs', (a.hitRate < 0.55 || a.hitRate > 0.9) && 'text-warn-ink')}>
                      {fmtPct(a.hitRate)}
                    </Td>
                  ))}
                  <Td numeric className="text-xs">
                    {acc[2].biasBays > 0 ? '+' : ''}
                    {acc[2].biasBays.toFixed(1)}
                  </Td>
                  <Td className="text-xs">{drift ? <span className="rounded-chip bg-warn-soft px-1.5 py-0.5 text-warn-ink">check</span> : <span className="text-muted">steady</span>}</Td>
                </tr>
              )
            })}
          </tbody>
        </Table>
      </div>
    </>
  )
}
